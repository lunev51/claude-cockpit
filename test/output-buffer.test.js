'use strict';
// Кольцевой буфер вывода: то, что клиент увидит в терминале, подключившись.
// Ограничение по байтам — не оптимизация, а условие жизни на 8 ГБ ОЗУ:
// без него вкладка с `npm test` в цикле съела бы память за ночь.
const test = require('node:test');
const assert = require('node:assert');
const { createOutputBuffer } = require('../src/main/output-buffer');

test('копит вывод вкладки и отдаёт склеенным', () => {
  const b = createOutputBuffer({ maxBytes: 1024 });
  b.push('T1', 'привет, ');
  b.push('T1', 'мир');
  assert.strictEqual(b.get('T1'), 'привет, мир');
});

test('вкладки не смешиваются', () => {
  const b = createOutputBuffer({ maxBytes: 1024 });
  b.push('T1', 'первая');
  b.push('T2', 'вторая');
  assert.strictEqual(b.get('T1'), 'первая');
  assert.strictEqual(b.get('T2'), 'вторая');
});

test('пустая вкладка — пустая строка, а не undefined', () => {
  const b = createOutputBuffer({ maxBytes: 1024 });
  assert.strictEqual(b.get('нет-такой'), '');
});

test('превышение предела режет НАЧАЛО — свежий хвост важнее', () => {
  const b = createOutputBuffer({ maxBytes: 10 });
  b.push('T1', 'абвгде');   // 12 байт в utf-8 (кириллица по 2)
  b.push('T1', 'жз');       // ещё 4
  const out = b.get('T1');
  assert.ok(Buffer.byteLength(out, 'utf8') <= 10, `осталось ${Buffer.byteLength(out, 'utf8')} байт`);
  assert.ok(out.endsWith('жз'), 'хвост обязан сохраниться');
});

test('одна порция длиннее предела обрезается до предела', () => {
  const b = createOutputBuffer({ maxBytes: 8 });
  b.push('T1', 'x'.repeat(100));
  assert.strictEqual(Buffer.byteLength(b.get('T1'), 'utf8'), 8);
});

test('обрезка не разрывает многобайтный символ пополам', () => {
  // Кириллица занимает 2 байта. Наивная резка по байтам даёт «замену» U+FFFD
  // прямо в первой строке, которую увидит человек на макбуке.
  //
  // Ре-ревью: с амортизацией (OVERSHOOT_FACTOR, см. output-buffer.js) обрезка
  // срабатывает не при ЛЮБОМ превышении maxBytes, а только при превышении
  // ЗАПАСА (maxBytes×1,25). 'абв' — 6 байт при maxBytes:5 — раньше хватало,
  // чтобы гарантированно войти в trimToBytesFromEnd; теперь 6 байт МЕНЬШЕ
  // запаса (6 байт), обрезка вообще не срабатывает, и тест «проходит» не
  // проверяя ничего (та же ловушка, что нашли у стража O(n²) ниже). Пушим
  // заведомо больше запаса, чтобы обрезка гарантированно случилась.
  const b = createOutputBuffer({ maxBytes: 5 });
  b.push('T1', 'абвгде'); // 12 байт — с запасом больше порога (floor(5*1.25)=6)
  const out = b.get('T1');
  assert.ok(Buffer.byteLength(out, 'utf8') <= 5, `обрезка не сработала: ${Buffer.byteLength(out, 'utf8')} байт`);
  assert.ok(!out.includes('�'), `битый символ: ${JSON.stringify(out)}`);
});

test('drop освобождает память закрытой вкладки', () => {
  const b = createOutputBuffer({ maxBytes: 1024 });
  b.push('T1', 'данные');
  b.drop('T1');
  assert.strictEqual(b.get('T1'), '');
  assert.strictEqual(b.totalBytes(), 0);
});

test('totalBytes считает все вкладки — им жить в одной памяти', () => {
  const b = createOutputBuffer({ maxBytes: 1024 });
  b.push('T1', 'abc');
  b.push('T2', 'de');
  assert.strictEqual(b.totalBytes(), 5);
});

// Ре-ревью (Important): амортизация (OVERSHOOT_FACTOR в output-buffer.js)
// делает контракт «хвост не длиннее maxBytes» МЯГКИМ — между двумя
// срабатываниями обрезки size() может ВРЕМЕННО превышать maxBytes. Жёсткая
// граница памяти теперь — maxBytes × OVERSHOOT_FACTOR (1,25), а не maxBytes
// ровно. Явный тест на эту границу — по прямому требованию ре-ревью ("это
// надо отразить... в тесте на память"), не косвенно через другой тест.
test('память вкладки никогда не превышает maxBytes × запас, даже под непрерывным потоком', () => {
  const maxBytes = 1024;
  const hardCeiling = Math.floor(maxBytes * 1.25); // 1280 — см. OVERSHOOT_FACTOR в output-buffer.js
  const b = createOutputBuffer({ maxBytes });
  let worstCase = 0;
  for (let i = 0; i < 500; i++) {
    b.push('T1', 'кусок вывода номер ' + i + ' '); // ASCII+кириллица вперемешку
    worstCase = Math.max(worstCase, b.size('T1'));
  }
  assert.ok(worstCase <= hardCeiling, `размер поднимался до ${worstCase} байт при жёсткой границе ${hardCeiling}`);
});

// Important 2 (ревью задачи 4): эмодзи в UTF-16 — суррогатная ПАРА (два
// code unit на одну кодовую точку), а не один символ. Резка по code unit
// (что делала брифовая реализация — по text.length, а не по codePointAt)
// может остановиться МЕЖДУ высоким и низким суррогатом — на проводе (после
// кодирования в UTF-8, ровно то, что уйдёт клиенту по сети) одинокий
// суррогат превращается в символ замены. Живой репро именно этого сценария —
// limit=11, три ракеты — воспроизведён в task-4-report.md: старый алгоритм
// давал [U+DE80(одинокий) U+1F680 U+1F680], wire_has_FFFD=true.
test('обрезка не разрывает суррогатную пару эмодзи пополам', () => {
  // Ре-ревью: та же ловушка амортизации, что у теста выше — 3 ракеты (12
  // байт) при maxBytes:11 меньше запаса (floor(11*1.25)=13), обрезка не
  // срабатывает, тест ничего не проверяет. Берём 4 ракеты (16 байт) —
  // заведомо больше запаса.
  const b = createOutputBuffer({ maxBytes: 11 });
  b.push('T1', '\u{1F680}\u{1F680}\u{1F680}\u{1F680}'); // четыре ракеты, по 4 байта UTF-8 / 2 code unit каждая
  const out = b.get('T1');
  assert.ok(Buffer.byteLength(out, 'utf8') <= 11, `обрезка не сработала: ${Buffer.byteLength(out, 'utf8')} байт`);
  // Проверяем то же, чем это ловит ревью: как строка ляжет НА ПРОВОД. Node
  // кодирует одинокий суррогат в UTF-8 как U+FFFD (замена) — если резка
  // разорвала пару, это всплывёт именно здесь, а не в JS-строке напрямую.
  const wire = Buffer.from(out, 'utf8').toString('utf8');
  assert.ok(!wire.includes('�'), `на проводе битый символ: ${JSON.stringify(out)}`);
});

// Ре-ревью (Important, новая находка): ПЕРВАЯ версия этого стража пушила
// 256×294 байта = 75 264 байта в ПУСТОЙ буфер с maxBytes:256*1024 — предел
// никогда не превышался, ветка обрезки (trimToBytesFromEnd) не исполнялась
// НИ РАЗУ, страж проходил и на старом, медленном коде за единицы миллисекунд.
// Страж стерёг пустоту. Исправление — методика ре-ревьюера: сначала ЗАБИТЬ
// буфер ДО предела (892 куска по 294 байта ≈ 262 144 байта = maxBytes), и
// только ПОТОМ измерять время следующих push — тогда ветка обрезки реально
// исполняется. Красноту проверил вручную (см. task-4-report.md): с временно
// возвращённым старым O(n²)-алгоритмом этот же сценарий даёт тысячи
// миллисекунд, здесь — доли секунды.
test('поток из сотен записей поверх УЖЕ ЗАПОЛНЕННОГО буфера не проваливается в O(n²) (страж от Critical 1)', () => {
  const b = createOutputBuffer({ maxBytes: 256 * 1024 });
  const frame = '─'.repeat(40) + '│';
  const chunk = 'Running task... [====>    ] 42% '.repeat(3) + frame + 'русский текст статуса выполнения задачи ';
  const chunkBytes = Buffer.byteLength(chunk, 'utf8'); // 294 байта
  // Прогрев: 892 × 294 ≈ 262 248 байт — буфер ДО измерения уже на пределе
  // (maxBytes:262 144), не в пустом состоянии.
  const prefillCount = Math.ceil((256 * 1024) / chunkBytes);
  for (let i = 0; i < prefillCount; i++) b.push('T1', chunk);
  const t0 = Date.now();
  for (let i = 0; i < 256; i++) b.push('T1', chunk); // 256×294=75 264 байта — заведомо больше запаса (65 536), обрезка гарантированно случится
  const elapsedMs = Date.now() - t0;
  assert.ok(elapsedMs < 2000, `256 push поверх заполненного буфера заняли ${elapsedMs} мс — похоже на регресс в O(n²)`);
  assert.ok(b.size('T1') <= Math.floor(256 * 1024 * 1.25), 'жёсткая граница памяти (maxBytes × запас) нарушена');
});

// Прямое продолжение находки выше: стоимость ОДНОЙ обрезки — O(maxBytes),
// амортизация размазывает её по объёму НОВЫХ данных, а не по числу push —
// значит на очень мелких кусках (крайний случай, из живого ConPTY почти
// недостижим, но не запрещён протоколом) обрезка всё ещё может сработать
// много раз подряд, если суммарный объём мелких кусков велик. Проверяем, что
// поток из тысяч однобайтовых push поверх заполненного буфера всё равно
// укладывается в разумный бюджет — без амортизации (полная привязка «одна
// обрезка на каждый push, где хоть один байт лишний») это было бы кратно
// медленнее (ре-ревью: 100 КБ кусками по 1 байту на неамортизированном коде
// — 39 432 мс).
test('поток из тысяч однобайтовых push поверх заполненного буфера не деградирует (амортизация обрезки)', () => {
  const b = createOutputBuffer({ maxBytes: 256 * 1024 });
  const filler = 'x'.repeat(256 * 1024); // сразу забиваем буфер до предела одним push
  b.push('T1', filler);
  const t0 = Date.now();
  for (let i = 0; i < 5000; i++) b.push('T1', 'ы'); // 2 байта каждый — суммарно 10 000 байт, часть push пересечёт запас
  const elapsedMs = Date.now() - t0;
  assert.ok(elapsedMs < 3000, `5000 однобайтовых-ish push заняли ${elapsedMs} мс`);
});
