'use strict';
// Кто сейчас за рулём. У pty один размер на всех клиентов, поэтому
// одновременных хозяев быть не может — эксклюзивность убирает целый слой
// согласования колонок и строк.
//
// Уход владельца НЕ передаёт управление: закрытая крышка макбука не должна
// разворачивать окно на ПК посреди ночи. Управление меняется только явным
// захватом — открытием страницы в браузере или показом окна на ПК.
// onChange({owner, previous, size}) — управление сменило хозяина.
// onPresence({owner, online}) — тот же хозяин пропал со связи или вернулся.
// Второе НЕ смена владельца: окно ПК не должно разворачиваться от того, что
// на макбуке закрыли крышку. Но знать об этом надо всем — раньше drop менял
// только внутренний флаг, и строка «(не на связи)» в трее и на заглушке была
// недостижима в проде, хотя тесты на неё были зелёные.
// Размер, который вообще можно запомнить: целые 2..500 по обеим осям — те же
// границы, что validDim в ipc.js отдаёт pty. C1 ревью: claim считал размером
// ЛЮБОЙ объект, и renderer без подогнанного терминала (загрузка страницы до
// первой вкладки) слал {cols: null, rows: null} — это затирало запомненный
// размер владельца, и следующая пересадка раздавала сессиям мусор. Кривое
// теперь значит то же, что отсутствующее: «размера не знаю».
function isValidSize(s) {
  const dim = (n) => Number.isInteger(n) && n >= 2 && n <= 500;
  return !!s && typeof s === 'object' && dim(s.cols) && dim(s.rows);
}

// Порог РАЗДАЧИ размера всем вкладкам: 40×10 — в такой сетке ещё можно
// читать и работать, а всё уже — временное сужение (диф-панель в узком
// браузере, перетаскивание края окна), ради которого нельзя перерисовывать
// все сессии и срезать прокрутку скрытых (ре-ревью: 14×27 при ~720px с
// диф-панелью). Копия — в src/renderer/js/term-size.js: по ней renderer
// решает, раздавать ли сетку скрытым xterm; равенство копий держит
// test/grid-share.test.js (ESM и CJS не импортируют один файл).
const MIN_SHARED_GRID = Object.freeze({ cols: 40, rows: 10 });

// Запомненный размер владельца нужен ТОЛЬКО для раздачи всем вкладкам:
// пересадка (applyHandoffSize в ipc.js) и старт скрытой вкладки
// (resolveStartSize). Поэтому запоминаем только раздаваемый: узкий размер
// видимой вкладки разошёлся бы всем при следующей пересадке. Остаётся
// последний раздаваемый — в нём main и держит остальные pty.
function isShareableSize(s) {
  return isValidSize(s) && s.cols >= MIN_SHARED_GRID.cols && s.rows >= MIN_SHARED_GRID.rows;
}

function createOwnership({ onChange, onPresence } = {}) {
  let owner = 'local';
  let online = true;
  // Размер помним ПО ВЛАДЕЛЬЦУ: окно ПК на весь экран и браузер на макбуке —
  // это два разных терминала. Возврат управления часто происходит без нового
  // размера (main.js забирает его при показе окна, когда renderer ещё не
  // успел сказать своё слово), и подставить туда чужой размер значило бы
  // перерисовать Claude Code в ширине другой машины на каждом возврате.
  const sizes = new Map();

  function claim(who, nextSize) {
    if (isShareableSize(nextSize)) sizes.set(who, { cols: nextSize.cols, rows: nextSize.rows });
    if (who === owner) {
      // Тот же хозяин вернулся после обрыва — смены владельца нет, но факт
      // «снова на связи» касается всех: у остальных клиентов на заглушке и в
      // трее висит «не на связи».
      const wasOffline = !online;
      online = true;
      if (wasOffline && typeof onPresence === 'function') onPresence({ owner, online: true });
      return false;
    }
    const previous = owner;
    // C2 ревью: прежний владелец ушёл со связи ДО смены — его сокет закрыт,
    // а имя сокета не возвращается никогда (перезагрузка страницы = новое
    // имя). Пока он был владельцем, размер держали ради скрытых вкладок;
    // теперь он не нужен никому. 'local' офлайн не уходит (drop зовёт только
    // net-server по закрытию сокета), его размер так не стирается.
    if (!online) sizes.delete(previous);
    owner = who;
    online = true;
    // Размер НОВОГО владельца, не прежнего: именно под него переразмеривается
    // pty. Незнакомый клиент без размера отдаёт null — лучше не трогать pty
    // вовсе, чем натянуть на него чужую раскладку (см. applyHandoffSize).
    if (typeof onChange === 'function') onChange({ owner, previous, size: sizes.get(who) || null });
    return true;
  }

  // Актуальный размер терминала текущего владельца. Живая жалоба 05.08: «при
  // возврате на ПК размер ломается, приходится дёргать окно». Размер попадал
  // сюда ТОЛЬКО через claim, то есть с загрузки страницы, — а человек потом
  // разворачивает окно, тянет край, меняет размер шрифта, и всё это уезжает в
  // pty мимо владения (term:resize). Возврат ставил pty в размер той самой
  // загрузки, Claude Code перерисовывался под чужую ширину, и вылечить это мог
  // только ручной ресайз окна: он будил наблюдателя, тот слал настоящий размер.
  //
  // Владельца и событий не трогаем — это не захват, а уточнение факта.
  // Кривой и узкий размер игнорируем (та же isShareableSize, что у claim):
  // скрытое окно даёт контейнер нулевого размера, узкое — 14×27, и запомнить
  // такое значило бы раздать его всем при следующем захвате.
  function noteSize(nextSize) {
    if (!isShareableSize(nextSize)) return;
    sizes.set(owner, { cols: nextSize.cols, rows: nextSize.rows });
  }

  function drop(who) {
    if (who !== owner) {
      // C2 ревью: ушедший невладелец не вернётся под тем же именем, а его
      // размер (если он когда-то держал руль) копился бы в карте на каждое
      // переподключение. Размер ВЛАДЕЛЬЦА не трогаем — см. ниже.
      sizes.delete(who);
      return false;
    }
    // Владельца НЕ меняем: обрыв связи не равен потере управления (закрытая
    // крышка макбука не должна разворачивать окно на ПК посреди ночи).
    const wasOnline = online;
    online = false;
    if (wasOnline && typeof onPresence === 'function') onPresence({ owner, online: false });
    return true;
  }

  return {
    owner: () => owner,
    size: () => sizes.get(owner) || null,
    ownerOnline: () => online,
    canWrite: (who) => who === owner,
    claim,
    noteSize,
    drop,
    // Сколько размеров в памяти — только ради теста утечки (C2 ревью): карта
    // приватная, а снаружи её рост не виден ничем, кроме памяти процесса.
    sizeCount: () => sizes.size,
  };
}

// isValidSize наружу — ради screen-mirror.js: зеркало экрана обязано совпадать
// с pty по размеру, и своё правило «валидного» там разошлось бы с этим.
module.exports = { createOwnership, MIN_SHARED_GRID, isShareableSize, isValidSize };
