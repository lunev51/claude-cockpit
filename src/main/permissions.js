'use strict';
// Что окну кокпита разрешено спрашивать у системы. Вынесено из main.js
// отдельным модулем ради теста: цена ошибки высока в обе стороны — лишнее
// разрешение отдаёт камеру или геолокацию странице, которая рендерит
// недоверенный вывод терминала, а недостающее молча ломает живую фичу.
//
// История файла в двух строках. Обработчик появился в фазе 9 под голосовой
// ввод и разрешал РОВНО микрофон, всё остальное отклонял. Через полгода
// пользователь сообщил: «не работает Ctrl+V… и Ctrl+Shift+V тоже». Замер
// отдельным Electron-приложением показал причину:
//   с обработчиком кокпита -> NotAllowedError: Read permission denied
//   без обработчика        -> буфер читается
// То есть вставка из буфера (Ctrl+Shift+V и правый клик — оба идут через
// navigator.clipboard.readText) была мертва целиком. Коварство в том, что
// navigator.permissions.query при этом отвечает 'granted': интерфейс говорит
// «разрешено», а фактическое чтение отклоняется обработчиком.
const ALLOWED = new Set([
  // Чтение буфера обмена: Ctrl+Shift+V и вставка правым кликом.
  'clipboard-read',
  // Запись буфера: копирование выделения из терминала. Chromium обычно не
  // спрашивает разрешения на неё, но если спросит — отказывать незачем.
  'clipboard-sanitized-write',
]);

function decidePermission(permission, details) {
  // В Electron 29 разрешение 'media' покрывает И микрофон, И камеру одним
  // именем — проверки одного имени мало. Список типов есть только у media-
  // запросов; recorder.js просит строго audio, поэтому легитимный запрос
  // кокпита никогда не содержит 'video'.
  if (permission === 'media') {
    const types = details && details.mediaTypes;
    return !(Array.isArray(types) && types.includes('video'));
  }
  return ALLOWED.has(permission);
}

module.exports = { decidePermission };
