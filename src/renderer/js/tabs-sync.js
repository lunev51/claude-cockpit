'use strict';
// Что делать, когда состав вкладок в main разошёлся с тем, что на экране.
//
// Живая жалоба 08.08: «открыл новую сессию на маке, вернулся на компьютер — её
// там нет, хотя она даже не пустая». Событие tabs:changed main рассылает всем
// клиентам с начала фазы (sessions.js: открытие, привязка сессии, закрытие), но
// в форме api его не было — интерфейс просто не подписывался. Состав вкладок
// расходился между машинами до перезагрузки страницы.
//
// Решение вынесено из app.js в чистый модуль не для красоты: ошибка здесь
// разбирает экран ЖИВОЙ сессии, а такую логику нельзя оставлять непокрытой.

// live — ответ tabs:list (массив живых вкладок main), known — tabId, которые
// сейчас показаны. Возвращает, кого добавить, кого убрать, и было ли вообще
// расхождение (чтобы не трогать интерфейс впустую).
export function diffTabs(live, known) {
  // Не массив — это не «вкладок нет», а «ответа нет»: обрыв связи, отказ
  // гарда, мусор в кадре. Разобрать по такому ответу живые сессии значило бы
  // стереть с экрана работу, которую никто не закрывал.
  if (!Array.isArray(live)) return { add: [], remove: [], changed: false };

  const liveIds = new Set();
  const add = [];
  for (const t of live) {
    if (!t || typeof t.tabId !== 'string' || !t.tabId) continue;
    liveIds.add(t.tabId);
    if (!known.includes(t.tabId)) add.push(t);
  }
  const remove = known.filter((id) => !liveIds.has(id));

  return { add, remove, changed: add.length > 0 || remove.length > 0 };
}
