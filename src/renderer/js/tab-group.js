'use strict';
// Раскладка вкладок по секциям сайдбара — чистая функция без DOM (тот же
// приём, что у peek-parse.js: renderer импортирует как ESM, тест дотягивается
// динамическим import()). Вынесено из tabs.js в живой приёмке 01.08, когда
// появилась секция «Наготове»: до этого решение «в какую секцию» было зашито
// в DOM-код и не проверялось ничем, а ошибка в нём — это ровно та жалоба,
// с которой всё началось («работают», хотя вкладка просто открыта»).

// Секции в порядке СРОЧНОСТИ — он же порядок сверху вниз в сайдбаре.
// «Наготове» последняя не по важности сессии, а потому, что требует ноль
// внимания: там лежит то, что живо, но ничего не просит.
export const GROUP_ORDER = ['waiting', 'working', 'done', 'trouble', 'ready'];

const GROUP_OF = {
  waiting: 'waiting',
  working: 'working',
  done: 'done',
  stuck: 'trouble',
  dead: 'trouble',
  ready: 'ready',
};

// Статуса ещё нет вовсе (вкладка только открыта, первый хук не пришёл) —
// «Наготове», а не «Работают»: она пока ничего не делает.
const GROUP_UNKNOWN = 'ready';

export function groupOf(status) {
  return GROUP_OF[status] || GROUP_UNKNOWN;
}
