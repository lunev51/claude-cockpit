// Кто сейчас за рулём — с точки зрения интерфейса. Чистая часть: DOM-обвязка
// живёт в app.js, здесь только решение «показывать заглушку и что на ней
// написать». Так эта логика попадает под node --test, которого у renderer нет
// (структурный пробел проекта: окно не тестируется, чистые модули — да).

// В Electron сетевого имени не бывает: окно ПК всегда 'local'. Браузер узнаёт
// своё имя из события net:hello сразу после подключения (а если событие
// разминулось с подпиской — из owner:get, см. app.js/refreshOwner).
export function selfId({ clientId } = {}) {
  return clientId || 'local';
}

// linked — жив ли сокет до самого кокпита (в Electron всегда true: окно и main
// живут одним процессом). I3 ревью: обрыв не показывался вообще — у зрителя
// висел прежний текст «Управление на другой машине», у владельца интерфейс
// молча замирал. Обрыв важнее вопроса о владельце: писать сейчас некуда
// никому, и кнопка захвата в этом состоянии врала бы (кадр уходит в мёртвый
// сокет — net-api.js/send на закрытом сокете no-op).
export function curtainState({
  owner, self, online, linked = true,
}) {
  if (!linked) {
    return {
      visible: true,
      title: 'Нет связи с кокпитом',
      hint: 'Переподключаюсь — страница обновится сама, как только кокпит ответит.',
      canTake: false,
    };
  }
  // owner пустой — ответа сервера ещё не было. Заглушка на первом кадре
  // напугала бы там, где всё в порядке. Пустые title/hint здесь не роскошь:
  // обвязка пишет их в DOM безусловно, и остатки прошлого текста мигнули бы
  // в момент возврата управления.
  if (!owner || owner === self) {
    return {
      visible: false, title: '', hint: '', canTake: false,
    };
  }
  return {
    visible: true,
    title: online ? 'Управление на другой машине' : 'Управление на другой машине (не на связи)',
    // Забрать управление можно и у пропавшего хозяина — иначе закрытая крышка
    // макбука запирала бы кокпит навсегда.
    hint: 'Можно смотреть. Чтобы писать — забрать управление себе.',
    canTake: true,
  };
}

// Можно ли прямо сейчас звать пишущий канал. null — можно; иначе причина и
// готовая фраза для тоста.
//
// I2 ревью: отклонение записи молчаливое на уровне протокола (спека), и у
// невладельца ✕ на вкладке/«+ Проект»/«Подключить хуки» либо тихо падали в
// unhandled rejection, либо (project:connect — свободный канал!) делали
// НЕХОРОШЕЕ у владельца за спиной. Отказ обязан быть видимым — но текст
// зависит от причины: «управление у соседа» и «связи вообще нет» человек
// лечит по-разному.
export function controlBlock({ owner, self, linked = true }) {
  if (!linked) return { reason: 'offline', message: 'нет связи с кокпитом, переподключаюсь' };
  // Владелец ещё неизвестен (первый кадр) — не блокируем: заглушки в этот
  // момент тоже нет, и запрещать вслепую значило бы ломать обычный старт.
  if (owner && owner !== self) {
    return { reason: 'handoff', message: 'управление на другой машине — забери его кнопкой на заглушке' };
  }
  return null;
}

// Забирать ли управление самим фактом загрузки страницы.
//
// Загрузок страницы ДВЕ разных, и намерение человека есть только у одной:
//   * человек сам открыл (или обновил) вкладку — правило спеки «последний
//     открывший владеет» про этот случай;
//   * страница перезагрузилась сама после обрыва связи (api-boot.js/
//     reconnectLoop зовёт location.reload(), когда кокпит снова отвечает) —
//     здесь никто ничего не решал, reloaded:true.
//
// C2 ре-ревью, живая цепочка: забытая вкладка на спящем макбуке → кокпит
// перезапустили → вкладка переподключилась, забрала руль → окно ПК спряталось
// в трей (main.js на смену владельца зовёт hideWindow), и вернуть его удалось
// только повторным запуском ярлыка. После автоперезагрузки захват уместен
// ровно тогда, когда за рулём никого нет: владелец не назван, владелец — мы
// сами, или владелец числится офлайн (online:false — он потерял связь тем же
// обрывом, и без этой ветки бывший владелец не вернул бы себе управление
// никогда). За рулём живой сосед — показываем заглушку и ждём человека.
//
// Сравнение с прежним собой после перезагрузки не работает: сервер выдаёт
// новое имя (cN+1) на каждое подключение.
//
// Для окна ПК ответ «нет» при любом чужом владельце: смена владельца на
// 'local' разворачивает окно на экран (main.js/showWindow), и при автозапуске
// оно вылезало бы посреди чужой работы (Critical соседнего ревью). Окно ПК
// берёт руль явно — показом из трея.
//
// intent — память вкладки о своей роли до перезагрузки ('claim' — была за
// рулём, 'view' — смотрела, null — первая загрузка/память не доехала). Она
// остаётся вторым, более слабым тормозом: восстановление сессии браузером
// (вкладка вернулась после краша) перезагрузкой себя не считает, а руль
// отбирать всё равно не должно.
export function shouldClaimOnLoad({
  owner, self, online = true, intent = null, reloaded = false,
}) {
  if (!owner) return true; // владельца никто не назвал — берём на себя
  if (owner === self) return true; // мы и так за рулём: захват лишь освежит размер
  if (self === 'local') return false; // окно ПК берёт руль только явно, из трея
  if (online === false) return true; // за рулём никого живого — руль свободен
  if (reloaded) return false; // перезагрузились сами, намерения не было
  return intent !== 'view';
}
