'use strict';
// «Пользователь СЕЙЧАС видит результат этой вкладки» — чистый предикат без
// DOM (тот же приём, что у tab-group.js и peek-parse.js: renderer импортирует
// как ESM, тест дотягивается динамическим import()).
//
// Это единственный барьер между «Готово — список непрочитанного» и «Готово
// всегда пустое», а зовут его из ТРЁХ мест app.js (переключение на вкладку,
// ответ на активной вкладке, возврат фокуса окну) — решать они обязаны
// одинаково, поэтому решение живёт здесь, а не размазано по вызовам.
//
// overlayCovering (Important 2 ревью 01.08): дашборд, палитра, поиск истории,
// форма рецепта, оверлей хоткеев и оверлей восстановления накрывают
// терминальную область ЦЕЛИКОМ. Ответ, пришедший под таким оверлеем, увиден
// не был — пометить его прочитанным значит потерять его из списка навсегда.
export function shouldMarkSeen({
  tabId, activeId, hasFocus, overlayCovering,
}) {
  if (!tabId || tabId !== activeId) return false; // смотрят другую вкладку
  if (!hasFocus) return false; // окно вообще не на экране
  if (overlayCovering) return false; // терминал накрыт — видеть было нечего
  return true;
}
