'use strict';
// Гарды подключения к УЖЕ существующим вкладкам (attachTab в app.js). Чистые
// функции отдельным модулем — по той же причине, что seen.js и
// voice-guards.js: решение можно проверить node --test, а app.js без DOM не
// тестируется вовсе.

// Поднимать ли pty вкладке, к которой мы подключаемся.
//
// Important (ре-ревью фикс-волны финального ревью): подключение
// переиспользует обычный путь создания терминала, а тот зовёт term.start
// безусловно — и sessions.js/start() на вкладке БЕЗ живого процесса делает
// spawn. Живьём: вкладка была alive:false, после подключения браузера стала
// alive:true с новым процессом.
//
// Почему это хуже обычного рестарта. Вкладка без процесса — штатная ситуация
// у владельца машины: сессия вышла по пятичасовому лимиту и стоит в
// «Проблемах». Спавн из подключения уходит БЕЗ --resume (флаг
// resumeOnFirstSpawn одноразовый и уже израсходован на первом спавне
// вкладки) — вместо продолжения работы поднимается чистая новая сессия, а
// старая теряется. Ctrl+Shift+R (sessions.js/restart) в том же положении
// резюмит известный sessionId, то есть подключение вело себя ХУЖЕ штатного
// рестарта. Плюс N мёртвых вкладок = N одновременных спавнов без стаггера.
//
// Мёртвую вкладку показываем как есть: строка в сайдбаре, её история из
// буфера вывода на экране, ввод заблокирован. Перезапускать или нет —
// решает человек.
//
// Отсутствующее/непонятное поле alive трактуем как «не живая»: цена ошибки
// несимметрична (лишний спавн теряет сессию, лишний отказ стартовать — это
// одно нажатие Ctrl+Shift+R).
export function shouldStartPty(tab) {
  return !!(tab && tab.alive === true);
}
