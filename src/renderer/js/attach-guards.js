'use strict';
// Гарды подключения к УЖЕ существующим вкладкам (attachTab в app.js). Чистые
// функции отдельным модулем — по той же причине, что seen.js и
// voice-guards.js: решение можно проверить node --test, а app.js без DOM не
// тестируется вовсе.

// Поднимать ли pty вкладке, к которой мы подключаемся.
//
// Important (ре-ревью фикс-волны финального ревью): подключение
// переиспользует обычный путь создания терминала, а тот зовёт term.start
// безусловно — и sessions.js/start() на вкладке БЕЗ живого процесса делает
// spawn. Живьём: вкладка была alive:false, после подключения браузера стала
// alive:true с новым процессом.
//
// Когда гард писался, главной причиной была потеря сессии: спавн из
// подключения уходил БЕЗ --resume. Теперь это закрыто слоем ниже — start()
// сам достраивает --resume известного sessionId (sessions.js/start,
// Important 2; тест «start для вкладки без процесса, но с привязанной
// сессией, ПРОДОЛЖАЕТ её» в test/sessions.test.js). Гард держится на
// остальных причинах:
//  - поднять мёртвую вкладку — решение человека, а не побочный эффект
//    подключения. Вкладка без процесса — штатная ситуация у владельца
//    машины: сессия вышла по пятичасовому лимиту и стоит в «Проблемах».
//    Браузер с макбука или Ctrl+R в окне не должны молча её перезапускать;
//  - sessionId известен не всегда (например, хук SessionStart так и не
//    пришёл). Тогда start() спавнит голые args — чистую новую сессию, а
//    Ctrl+Shift+R в том же положении открывает пикер --resume, если прошлый
//    резюм не проваливался (sessions.js/restart): человек выбрал бы сессию
//    сам, подключение выбрало бы за него;
//  - N мёртвых вкладок = N одновременных спавнов без стаггера.
//
// Мёртвую вкладку показываем как есть: строка в сайдбаре, её история из
// буфера вывода на экране, ввод заблокирован. Перезапускать или нет —
// решает человек.
//
// Отсутствующее/непонятное поле alive трактуем как «не живая»: цена ошибки
// несимметрична (лишний спавн поднимает процесс без спроса, а без известного
// sessionId — ещё и чистую сессию; лишний отказ стартовать — это одно
// нажатие Ctrl+Shift+R).
export function shouldStartPty(tab) {
  return !!(tab && tab.alive === true);
}

// Подпись мёртвой вкладки в терминале (attachTab в app.js) — по тому, что на
// деле сделает Ctrl+Shift+R (T1). Раньше всегда «продолжит сессию», а
// restart() продолжает её, только зная id; без него открывает пикер сессий, а
// после провала резюма поднимает чистую новую. Что именно — решает main
// (sessions.js/restartMode) и отдаёт в tabs:list полем restartMode; здесь
// только слова. Поля нет — не обещаем ничего конкретного.
const RESTART_HINTS = {
  resume: 'Ctrl+Shift+R продолжит сессию',
  picker: 'Ctrl+Shift+R откроет выбор сессии',
  fresh: 'Ctrl+Shift+R начнёт новую сессию',
};
export function deadTabHint(tab) {
  const hint = RESTART_HINTS[tab && tab.restartMode] || 'Ctrl+Shift+R перезапустит вкладку';
  return `процесс не запущен · ${hint}`;
}
